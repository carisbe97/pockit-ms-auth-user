package com.pockit.finance.auth.security.infrastructure.out.crypto;

import com.pockit.finance.auth.common.domain.exceptions.BaseDomainException;
import com.pockit.finance.auth.common.infrastructure.utilities.BaseConstants;
import com.pockit.finance.auth.security.domain.models.EncryptedPayload;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import javax.crypto.Cipher;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.OAEPParameterSpec;
import javax.crypto.spec.PSource;
import java.nio.charset.StandardCharsets;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.SecureRandom;
import java.security.spec.MGF1ParameterSpec;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.Base64;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class RsaAesGcmCryptoAdapterTest {

    private static final Instant FIXED_NOW = Instant.parse("2026-11-19T12:00:00Z");

    private KeyPair keyPair;
    private RsaAesGcmCryptoAdapter adapter;

    @BeforeEach
    void setUp() throws Exception {
        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        keyPair = generator.generateKeyPair();
        adapter = new RsaAesGcmCryptoAdapter(keyPair, 300, Clock.fixed(FIXED_NOW, ZoneOffset.UTC));
    }

    @Test
    @DisplayName("Debe descifrar correctamente un payload hibrido AES-256-GCM + RSA-2048 OAEP SHA-256")
    void shouldDecryptValidHybridPayload() throws Exception {
        String plainJson = "{\"correo\":\"camilo@pockit.com\",\"password\":\"Pockit2026*\"}";
        EncryptedPayload payload = encrypt(plainJson, FIXED_NOW.getEpochSecond());

        String result = adapter.decryptPayload(payload);

        assertThat(result).isEqualTo(plainJson);
        assertThat(adapter.getAlgorithm()).isEqualTo(BaseConstants.RSA_OAEP_ALGORITHM);
        assertThat(adapter.getPublicKeyBase64()).isNotBlank();
    }

    @Test
    @DisplayName("Debe cargar llaves RSA configuradas desde Base64 PKCS#8 y X.509")
    void shouldLoadConfiguredKeyPairFromBase64() throws Exception {
        String privBase64 = Base64.getEncoder().encodeToString(keyPair.getPrivate().getEncoded());
        String pubBase64 = Base64.getEncoder().encodeToString(keyPair.getPublic().getEncoded());

        RsaAesGcmCryptoAdapter loadedAdapter = new RsaAesGcmCryptoAdapter(privBase64, pubBase64, 300);
        assertThat(loadedAdapter.getPublicKeyBase64()).isEqualTo(pubBase64);

        RsaAesGcmCryptoAdapter autoGenerated = new RsaAesGcmCryptoAdapter("", "", 300);
        assertThat(autoGenerated.getPublicKeyBase64()).isNotBlank();

        assertThatThrownBy(() -> new RsaAesGcmCryptoAdapter("not-valid-base64!", pubBase64, 300))
                .isInstanceOf(IllegalStateException.class);
    }

    @Test
    @DisplayName("Debe rechazar payload expirado o futuro fuera de la ventana anti-replay")
    void shouldRejectExpiredOrFutureTimestamp() throws Exception {
        EncryptedPayload expired = encrypt("{}", FIXED_NOW.getEpochSecond() - 301);
        EncryptedPayload future = encrypt("{}", FIXED_NOW.getEpochSecond() + 301);

        assertThatThrownBy(() -> adapter.decryptPayload(expired))
                .isInstanceOf(BaseDomainException.class)
                .satisfies(ex -> {
                    BaseDomainException domainEx = (BaseDomainException) ex;
                    assertThat(domainEx.getStatusCode()).isEqualTo(400);
                    assertThat(domainEx.getCode()).isEqualTo(BaseConstants.CODE_PAYLOAD_EXPIRADO);
                });

        assertThatThrownBy(() -> adapter.decryptPayload(future))
                .isInstanceOf(BaseDomainException.class)
                .satisfies(ex -> assertThat(((BaseDomainException) ex).getCode())
                        .isEqualTo(BaseConstants.CODE_PAYLOAD_EXPIRADO));
    }

    @Test
    @DisplayName("Debe rechazar payload alterado (AuthTag GCM), IV invalido o campos nulos")
    void shouldRejectTamperedOrInvalidPayloads() throws Exception {
        EncryptedPayload valid = encrypt("{\"ok\":true}", FIXED_NOW.getEpochSecond());

        // Alterar 1 byte del cipherText
        byte[] tamperedBytes = Base64.getDecoder().decode(valid.cipherText());
        tamperedBytes[0] ^= 0x01;
        EncryptedPayload tampered = new EncryptedPayload(
                valid.encryptedKey(),
                valid.iv(),
                Base64.getEncoder().encodeToString(tamperedBytes),
                valid.timestamp()
        );

        assertThatThrownBy(() -> adapter.decryptPayload(tampered))
                .isInstanceOf(BaseDomainException.class)
                .satisfies(ex -> assertThat(((BaseDomainException) ex).getCode())
                        .isEqualTo(BaseConstants.CODE_PAYLOAD_INTEGRIDAD_INVALIDA));

        // IV con longitud incorrecta
        EncryptedPayload badIv = new EncryptedPayload(
                valid.encryptedKey(),
                Base64.getEncoder().encodeToString(new byte[8]),
                valid.cipherText(),
                valid.timestamp()
        );
        assertThatThrownBy(() -> adapter.decryptPayload(badIv))
                .isInstanceOf(BaseDomainException.class)
                .satisfies(ex -> assertThat(((BaseDomainException) ex).getCode())
                        .isEqualTo(BaseConstants.CODE_PAYLOAD_INTEGRIDAD_INVALIDA));

        // Campos nulos o vacios
        assertThatThrownBy(() -> adapter.decryptPayload(null))
                .isInstanceOf(BaseDomainException.class);
        assertThatThrownBy(() -> adapter.decryptPayload(new EncryptedPayload("", valid.iv(), valid.cipherText(), FIXED_NOW.getEpochSecond())))
                .isInstanceOf(BaseDomainException.class);
    }

    private EncryptedPayload encrypt(String plainJson, long timestamp) throws Exception {
        KeyGenerator aesGen = KeyGenerator.getInstance("AES");
        aesGen.init(256);
        SecretKey aesKey = aesGen.generateKey();

        byte[] iv = new byte[12];
        new SecureRandom().nextBytes(iv);

        Cipher aesCipher = Cipher.getInstance("AES/GCM/NoPadding");
        aesCipher.init(Cipher.ENCRYPT_MODE, aesKey, new GCMParameterSpec(128, iv));
        byte[] cipherBytes = aesCipher.doFinal(plainJson.getBytes(StandardCharsets.UTF_8));

        Cipher rsaCipher = Cipher.getInstance("RSA/ECB/OAEPWithSHA-256AndMGF1Padding");
        OAEPParameterSpec oaepSpec = new OAEPParameterSpec(
                "SHA-256",
                "MGF1",
                MGF1ParameterSpec.SHA256,
                PSource.PSpecified.DEFAULT
        );
        rsaCipher.init(Cipher.ENCRYPT_MODE, keyPair.getPublic(), oaepSpec);
        byte[] encryptedKey = rsaCipher.doFinal(aesKey.getEncoded());

        return new EncryptedPayload(
                Base64.getEncoder().encodeToString(encryptedKey),
                Base64.getEncoder().encodeToString(iv),
                Base64.getEncoder().encodeToString(cipherBytes),
                timestamp
        );
    }
}
